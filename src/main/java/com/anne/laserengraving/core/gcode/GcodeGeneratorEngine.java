package com.anne.laserengraving.core.gcode;

import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * G-code Generator Engine: Chuyển đổi ma trận nhị phân raster thành tập lệnh G-code chuẩn GRBL Laser Mode
 */
@Service
@RequiredArgsConstructor
public class GcodeGeneratorEngine {

    private final GcodeSafetyValidator safetyValidator;

    public GcodeModel generateRasterGcode(
            int[][] binaryMatrix,
            int widthPx,
            int heightPx,
            double originXMm,
            double originYMm,
            double targetWidthMm,
            double targetHeightMm,
            int speed,
            int power,
            int dpi) {

        // 1. Kiểm tra tham số an toàn
        safetyValidator.validateParameters(originXMm, originYMm, targetWidthMm, targetHeightMm, speed, power, dpi);

        double pixelStepMm = 25.4 / dpi;
        List<String> lines = new ArrayList<>();

        // 2. Thêm khối Header an toàn
        lines.add("; --- G-CODE GENERATED BY LASER ENGRAVING WEB APP ---");
        lines.add(String.format(Locale.US, "; Image Size: %d x %d px | Target: %.2f x %.2f mm | DPI: %d",
                widthPx, heightPx, targetWidthMm, targetHeightMm, dpi));
        lines.add(String.format(Locale.US, "; Origin: (X=%.2f, Y=%.2f) mm | Feedrate: %d mm/min | Laser Power: %d (PWM)",
                originXMm, originYMm, speed, power));
        lines.add("G21         ; Đơn vị đo Millimeter");
        lines.add("G90         ; Tọa độ tuyệt đối");
        lines.add("$32=1       ; Bật GRBL Laser Mode");
        lines.add("G0 F3000    ; Tốc độ chạy nhanh không tải");
        lines.add("M5          ; Đảm bảo tắt laser ban đầu");

        boolean laserActive = false;
        double totalTravelMm = 0.0;
        double lastX = originXMm;
        double lastY = originYMm;

        // 3. Quét Raster (quét từng dòng Y từ dưới lên trên: y = heightPx - 1 down to 0)
        for (int y = heightPx - 1; y >= 0; y--) {
            double currentYMm = originYMm + ((heightPx - 1 - y) * pixelStepMm);

            int x = 0;
            while (x < widthPx) {
                // Bỏ qua các điểm trắng (0)
                if (binaryMatrix[x][y] == 0) {
                    if (laserActive) {
                        lines.add("M5");
                        laserActive = false;
                    }
                    x++;
                    continue;
                }

                // Tìm đoạn các điểm đen (1) liên tục (Run-length compression)
                int startX = x;
                while (x < widthPx && binaryMatrix[x][y] == 1) {
                    x++;
                }
                int endX = x - 1;

                double startXMm = originXMm + (startX * pixelStepMm);
                double endXMm = originXMm + ((endX + 1) * pixelStepMm);

                // Di chuyển nhanh đến điểm bắt đầu nếu laser đang tắt
                if (!laserActive) {
                    lines.add(String.format(Locale.US, "G0 X%.3f Y%.3f", startXMm, currentYMm));
                    totalTravelMm += Math.hypot(startXMm - lastX, currentYMm - lastY);
                    lastX = startXMm;
                    lastY = currentYMm;
                }

                // Khắc đoạn từ startXMm đến endXMm
                if (!laserActive) {
                    lines.add(String.format(Locale.US, "G1 X%.3f Y%.3f F%d M3 S%d", endXMm, currentYMm, speed, power));
                    laserActive = true;
                } else {
                    lines.add(String.format(Locale.US, "G1 X%.3f Y%.3f", endXMm, currentYMm));
                }

                totalTravelMm += (endXMm - startXMm);
                lastX = endXMm;
            }

            // Kết thúc dòng quét, tắt laser
            if (laserActive) {
                lines.add("M5");
                laserActive = false;
            }
        }

        // 4. Thêm khối Footer an toàn
        lines.add("; --- FOOTER KẾT THÚC GIA CÔNG ---");
        lines.add("M5          ; Tắt chùm tia Laser");
        lines.add("G0 X0.000 Y0.000 ; Quay về tọa độ gốc");
        lines.add("M2          ; Kết thúc chương trình");

        // 5. Kiểm tra an toàn dòng lệnh
        safetyValidator.validateGcodeLines(lines);

        // 6. Đóng gói kết quả
        String fullContent = String.join("\r\n", lines) + "\r\n";
        byte[] bytes = fullContent.getBytes(StandardCharsets.UTF_8);

        // Ước tính thời gian gia công (giây): (Quãng đường mm / tốc độ mm/min) * 60 + phụ phí tăng giảm tốc
        int estimatedSeconds = (int) Math.round((totalTravelMm / speed) * 60 * 1.15) + 5;

        List<String> preview = lines.subList(0, Math.min(30, lines.size()));

        return GcodeModel.builder()
                .fullGcodeContent(fullContent)
                .totalLines(lines.size())
                .fileSizeBytes(bytes.length)
                .actualWidthMm(widthPx * pixelStepMm)
                .actualHeightMm(heightPx * pixelStepMm)
                .estimatedTimeSeconds(estimatedSeconds)
                .previewSnippet(preview)
                .build();
    }

    /**
     * Phương thức tương thích ngược khi không truyền tọa độ gốc (mặc định tại 0, 0)
     */
    public GcodeModel generateRasterGcode(
            int[][] binaryMatrix,
            int widthPx,
            int heightPx,
            double targetWidthMm,
            double targetHeightMm,
            int speed,
            int power,
            int dpi) {
        return generateRasterGcode(binaryMatrix, widthPx, heightPx, 0.0, 0.0, targetWidthMm, targetHeightMm, speed, power, dpi);
    }
}
